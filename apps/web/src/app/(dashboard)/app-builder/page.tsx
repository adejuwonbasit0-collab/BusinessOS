'use client';

import { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { portalsApi, formsApi, tablesApi } from '@/lib/phase3Api';
import { aiApi } from '@/lib/aiApi';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Textarea } from '@/components/ui/textarea';
import { Badge } from '@/components/ui/badge';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Dialog, DialogContent, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { Switch } from '@/components/ui/switch';
import {
  Layout, Plus, Sparkles, Globe, Users, Briefcase,
  FileText, Database, Loader2, Trash2, ExternalLink,
  CheckCircle, Settings, Table,
} from 'lucide-react';
import { toast } from '@/hooks/useToast';
import { cn } from '@/lib/utils';

const PORTAL_TYPE_CONFIG = {
  customer: { label: 'Customer Portal', icon: Users, color: 'bg-blue-500/10 text-blue-500', desc: 'Self-service portal for your customers' },
  staff: { label: 'Staff Portal', icon: Briefcase, color: 'bg-violet-500/10 text-violet-500', desc: 'Internal tools for your team' },
  vendor: { label: 'Vendor Portal', icon: Globe, color: 'bg-teal-500/10 text-teal-500', desc: 'Supplier and partner access' },
  internal: { label: 'Internal Tool', icon: Settings, color: 'bg-amber-500/10 text-amber-500', desc: 'Custom internal dashboards' },
};

const FIELD_TYPES = [
  { value: 'text', label: 'Short Text' }, { value: 'textarea', label: 'Long Text' },
  { value: 'email', label: 'Email' }, { value: 'phone', label: 'Phone' },
  { value: 'number', label: 'Number' }, { value: 'date', label: 'Date' },
  { value: 'select', label: 'Dropdown' }, { value: 'radio', label: 'Radio buttons' },
  { value: 'checkbox', label: 'Checkbox' }, { value: 'file', label: 'File upload' },
];

export default function AppBuilderPage() {
  const qc = useQueryClient();
  const [portalOpen, setPortalOpen] = useState(false);
  const [formOpen, setFormOpen] = useState(false);
  const [editingFormId, setEditingFormId] = useState<string | null>(null);
  const [tableOpen, setTableOpen] = useState(false);
  const [aiPrompt, setAiPrompt] = useState('');
  const [portalForm, setPortalForm] = useState({ name: '', type: 'customer', description: '' });
  const [newForm, setNewForm] = useState({ name: '', description: '', fields: [] as any[] });
  const [newTable, setNewTable] = useState({ name: '', label: '', fields: [] as any[] });

  const { data: portalsData } = useQuery({ queryKey: ['portals'], queryFn: portalsApi.list });
  const { data: formsData } = useQuery({ queryKey: ['forms'], queryFn: formsApi.list });
  const { data: tablesData } = useQuery({ queryKey: ['tables'], queryFn: tablesApi.list });

  const createPortalMutation = useMutation({
    mutationFn: portalsApi.create,
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['portals'] }); toast({ title: 'Portal created' }); setPortalOpen(false); },
    onError: (e: any) => toast({ title: e.message, variant: 'destructive' }),
  });

  const aiPortalMutation = useMutation({
    mutationFn: ({ type, desc }: { type: string; desc: string }) => portalsApi.generate(type, desc),
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['portals'] }); toast({ title: 'Portal generated by AI!' }); setAiPrompt(''); },
    onError: (e: any) => toast({ title: e.message, variant: 'destructive' }),
  });

  const createFormMutation = useMutation({
    mutationFn: formsApi.create,
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['forms'] }); toast({ title: 'Form created' }); setFormOpen(false); },
    onError: (e: any) => toast({ title: e.message, variant: 'destructive' }),
  });
  const updateFormMutation = useMutation({
    mutationFn: ({ id, data }: { id: string; data: any }) => formsApi.update(id, data),
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['forms'] }); toast({ title: 'Form updated' }); setFormOpen(false); setEditingFormId(null); },
    onError: (e: any) => toast({ title: e.message || 'Could not update form', variant: 'destructive' }),
  });

  const aiFormMutation = useMutation({
    mutationFn: (purpose: string) => formsApi.generate(purpose),
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['forms'] }); toast({ title: 'Form generated by AI!' }); },
    onError: (e: any) => toast({ title: e.message, variant: 'destructive' }),
  });

  const createTableMutation = useMutation({
    mutationFn: tablesApi.create,
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['tables'] }); toast({ title: 'Table created' }); setTableOpen(false); },
    onError: (e: any) => toast({ title: e.message, variant: 'destructive' }),
  });

  const deleteFormMutation = useMutation({
    mutationFn: formsApi.delete,
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['forms'] }); toast({ title: 'Form deleted' }); },
  });

  const deleteTableMutation = useMutation({
    mutationFn: tablesApi.delete,
    onSuccess: () => { qc.invalidateQueries({ queryKey: ['tables'] }); toast({ title: 'Table deleted' }); },
  });

  const portals = (portalsData as any)?.data?.portals || [];
  const forms = (formsData as any)?.data?.forms || [];
  const tables = (tablesData as any)?.data?.tables || [];

  const addFormField = () => setNewForm(p => ({ ...p, fields: [...p.fields, { label: '', type: 'text', required: false, options: '' }] }));
  const removeFormField = (i: number) => setNewForm(p => ({ ...p, fields: p.fields.filter((_, idx) => idx !== i) }));

  const addTableField = () => setNewTable(p => ({ ...p, fields: [...p.fields, { name: '', type: 'text', label: '' }] }));
  const removeTableField = (i: number) => setNewTable(p => ({ ...p, fields: p.fields.filter((_, idx) => idx !== i) }));

  return (
    <div className="space-y-6">
      <div className="flex items-start justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold tracking-tight flex items-center gap-2"><Layout className="h-6 w-6 text-violet-500" />App Builder</h1>
          <p className="text-sm text-muted-foreground mt-1">Build portals, forms, and databases without writing code</p>
        </div>
      </div>

      <Tabs defaultValue="portals">
        <TabsList>
          <TabsTrigger value="portals"><Layout className="h-3.5 w-3.5 mr-1.5" />Portals</TabsTrigger>
          <TabsTrigger value="forms"><FileText className="h-3.5 w-3.5 mr-1.5" />Forms</TabsTrigger>
          <TabsTrigger value="tables"><Database className="h-3.5 w-3.5 mr-1.5" />Databases</TabsTrigger>
        </TabsList>

        {/* ── Portals ── */}
        <TabsContent value="portals" className="mt-4 space-y-4">
          <div className="grid sm:grid-cols-2 gap-4">
            <Card className="border-dashed">
              <CardContent className="pt-5 space-y-3">
                <p className="text-sm font-semibold flex items-center gap-2"><Sparkles className="h-4 w-4 text-blue-500" />Generate with AI</p>
                <Textarea value={aiPrompt} onChange={(e) => setAiPrompt(e.target.value)} placeholder="E.g. A customer portal where clients can view invoices, track orders, and submit support tickets" rows={3} className="resize-none text-sm" />
                <div className="flex gap-2">
                  {(['customer', 'staff', 'vendor'] as const).map((type) => (
                    <Button key={type} size="sm" variant="outline" className="flex-1 text-xs capitalize"
                      onClick={() => aiPortalMutation.mutate({ type, desc: aiPrompt })} disabled={!aiPrompt.trim() || aiPortalMutation.isPending}>
                      {aiPortalMutation.isPending ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : type}
                    </Button>
                  ))}
                </div>
              </CardContent>
            </Card>
            <Card className="border-dashed cursor-pointer hover:border-primary/30 transition-colors" onClick={() => setPortalOpen(true)}>
              <CardContent className="pt-5 flex flex-col items-center justify-center text-center py-8">
                <Plus className="h-8 w-8 text-muted-foreground/40 mb-2" />
                <p className="font-medium text-sm">Create manually</p>
                <p className="text-xs text-muted-foreground mt-1">Choose type and configure</p>
              </CardContent>
            </Card>
          </div>

          <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {portals.map((portal: any) => {
              const cfg = PORTAL_TYPE_CONFIG[portal.type as keyof typeof PORTAL_TYPE_CONFIG] || PORTAL_TYPE_CONFIG.internal;
              const Icon = cfg.icon;
              return (
                <Card key={portal.id} className="hover:border-primary/30 transition-colors">
                  <CardContent className="pt-5">
                    <div className="flex items-start justify-between mb-3">
                      <div className={cn('w-10 h-10 rounded-xl flex items-center justify-center', cfg.color)}><Icon className="h-5 w-5" /></div>
                      <Badge variant="outline" className="text-[10px] capitalize">{portal.is_published ? 'Live' : 'Draft'}</Badge>
                    </div>
                    <h3 className="font-semibold text-sm">{portal.name}</h3>
                    <p className="text-xs text-muted-foreground mt-0.5">{cfg.label}</p>
                    <div className="flex gap-2 mt-3">
                      <Button size="sm" variant="outline" className="flex-1 h-7 text-xs"><Settings className="h-3 w-3 mr-1" />Edit</Button>
                      <Button size="sm" variant="outline" className="h-7 text-xs"><ExternalLink className="h-3 w-3" /></Button>
                    </div>
                  </CardContent>
                </Card>
              );
            })}
          </div>
        </TabsContent>

        {/* ── Forms ── */}
        <TabsContent value="forms" className="mt-4 space-y-4">
          <div className="flex items-center gap-3">
            <Button size="sm" onClick={() => setFormOpen(true)}><Plus className="h-4 w-4 mr-2" />New Form</Button>
            <div className="relative flex-1 max-w-xs">
              <Input placeholder="Describe a form to generate with AI…" className="pr-20 text-sm"
                onKeyDown={(e) => { if (e.key === 'Enter') aiFormMutation.mutate((e.target as HTMLInputElement).value); }} />
              <Button size="sm" variant="ghost" className="absolute right-1 top-1/2 -translate-y-1/2 h-7 text-xs gap-1"
                onClick={() => toast({ title: 'Type a form description and press Enter' })}><Sparkles className="h-3.5 w-3.5" />AI</Button>
            </div>
          </div>

          <div className="rounded-xl border bg-card divide-y">
            {forms.length === 0 ? (
              <div className="text-center py-12 text-muted-foreground"><FileText className="h-8 w-8 mx-auto mb-2 opacity-30" />No forms yet</div>
            ) : forms.map((form: any) => (
              <div key={form.id} className="flex items-center gap-3 p-4">
                <div className="w-9 h-9 rounded-lg bg-teal-500/10 text-teal-500 flex items-center justify-center"><FileText className="h-4 w-4" /></div>
                <div className="flex-1 min-w-0">
                  <p className="font-medium text-sm">{form.name}</p>
                  <p className="text-xs text-muted-foreground">{form.submission_count || 0} submissions · {form.is_published ? 'Published' : 'Draft'}</p>
                </div>
                <div className="flex gap-2">
                  <Button size="sm" variant="outline" className="h-7 text-xs" onClick={() => { const fields = typeof form.fields === 'string' ? JSON.parse(form.fields) : (form.fields || []); setNewForm({ name: form.name, description: form.description || '', fields }); setEditingFormId(form.id); setFormOpen(true); }}>Edit</Button>
                  <Button size="sm" variant="ghost" className="h-7 w-7 text-destructive p-0" onClick={() => deleteFormMutation.mutate(form.id)}><Trash2 className="h-3.5 w-3.5" /></Button>
                </div>
              </div>
            ))}
          </div>
        </TabsContent>

        {/* ── Databases ── */}
        <TabsContent value="tables" className="mt-4 space-y-4">
          <Button size="sm" onClick={() => setTableOpen(true)}><Plus className="h-4 w-4 mr-2" />New Table</Button>

          <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {tables.length === 0 ? (
              <div className="col-span-full text-center py-12 text-muted-foreground border-2 border-dashed rounded-xl"><Database className="h-8 w-8 mx-auto mb-2 opacity-30" />No custom tables yet</div>
            ) : tables.map((table: any) => {
              const fields = typeof table.fields === 'string' ? JSON.parse(table.fields) : (table.fields || []);
              return (
                <Card key={table.id} className="hover:border-primary/30 transition-colors">
                  <CardContent className="pt-5">
                    <div className="flex items-start justify-between mb-2">
                      <div className="w-9 h-9 rounded-lg bg-indigo-500/10 text-indigo-500 flex items-center justify-center"><Table className="h-4 w-4" /></div>
                    </div>
                    <h3 className="font-semibold text-sm">{table.label}</h3>
                    <p className="text-xs text-muted-foreground mt-0.5">{fields.length} fields</p>
                    <div className="flex gap-2 mt-3">
                      <Button size="sm" variant="outline" className="flex-1 h-7 text-xs">Open</Button>
                      <Button size="sm" variant="ghost" className="h-7 w-7 text-destructive p-0" onClick={() => deleteTableMutation.mutate(table.id)}><Trash2 className="h-3.5 w-3.5" /></Button>
                    </div>
                  </CardContent>
                </Card>
              );
            })}
          </div>
        </TabsContent>
      </Tabs>

      {/* ── Create Portal Dialog ── */}
      <Dialog open={portalOpen} onOpenChange={setPortalOpen}>
        <DialogContent>
          <DialogHeader><DialogTitle>Create Portal</DialogTitle></DialogHeader>
          <div className="space-y-4 py-1">
            <div className="space-y-1.5"><Label>Name</Label><Input value={portalForm.name} onChange={(e) => setPortalForm(p => ({ ...p, name: e.target.value }))} placeholder="My Customer Portal" /></div>
            <div className="space-y-1.5"><Label>Type</Label>
              <div className="grid grid-cols-2 gap-2">
                {Object.entries(PORTAL_TYPE_CONFIG).map(([key, cfg]) => {
                  const Icon = cfg.icon;
                  return (
                    <button key={key} onClick={() => setPortalForm(p => ({ ...p, type: key }))}
                      className={cn('flex items-center gap-2 p-3 rounded-lg border text-left transition-all', portalForm.type === key ? 'border-primary bg-primary/5' : 'hover:border-primary/30')}>
                      <div className={cn('w-7 h-7 rounded-lg flex items-center justify-center', cfg.color)}><Icon className="h-3.5 w-3.5" /></div>
                      <div><p className="text-xs font-medium">{cfg.label}</p></div>
                    </button>
                  );
                })}
              </div>
            </div>
            <div className="space-y-1.5"><Label>Description</Label><Textarea value={portalForm.description} onChange={(e) => setPortalForm(p => ({ ...p, description: e.target.value }))} rows={2} className="resize-none" /></div>
            <div className="flex justify-end gap-2">
              <Button variant="outline" onClick={() => setPortalOpen(false)}>Cancel</Button>
              <Button onClick={() => createPortalMutation.mutate(portalForm)} disabled={!portalForm.name || createPortalMutation.isPending}>
                {createPortalMutation.isPending && <Loader2 className="h-4 w-4 mr-2 animate-spin" />}Create Portal
              </Button>
            </div>
          </div>
        </DialogContent>
      </Dialog>

      {/* ── Create Form Dialog ── */}
      <Dialog open={formOpen} onOpenChange={setFormOpen}>
        <DialogContent className="max-w-xl max-h-[80vh] overflow-y-auto">
          <DialogHeader><DialogTitle>{editingFormId ? 'Edit Form' : 'Create Form'}</DialogTitle></DialogHeader>
          <div className="space-y-4 py-1">
            <div className="space-y-1.5"><Label>Form Name</Label><Input value={newForm.name} onChange={(e) => setNewForm(p => ({ ...p, name: e.target.value }))} /></div>
            <div className="space-y-2">
              <div className="flex items-center justify-between"><Label>Fields</Label><Button size="sm" variant="outline" className="h-7 text-xs" onClick={addFormField}><Plus className="h-3.5 w-3.5 mr-1" />Add Field</Button></div>
              <div className="space-y-2 max-h-48 overflow-y-auto">
                {newForm.fields.map((field, i) => (
                  <div key={i} className="space-y-2">
                  <div className="flex items-center gap-2">
                    <Input value={field.label} onChange={(e) => setNewForm(p => ({ ...p, fields: p.fields.map((f, idx) => idx === i ? { ...f, label: e.target.value } : f) }))} placeholder="Field label" className="flex-1" />
                    <Select value={field.type} onValueChange={(v) => setNewForm(p => ({ ...p, fields: p.fields.map((f, idx) => idx === i ? { ...f, type: v } : f) }))}>
                      <SelectTrigger className="w-32"><SelectValue /></SelectTrigger>
                      <SelectContent>{FIELD_TYPES.map((t) => <SelectItem key={t.value} value={t.value}>{t.label}</SelectItem>)}</SelectContent>
                    </Select>
                    <label className="flex items-center gap-1 text-xs whitespace-nowrap"><input type="checkbox" checked={Boolean(field.required)} onChange={(e) => setNewForm(p => ({ ...p, fields: p.fields.map((f, idx) => idx === i ? { ...f, required: e.target.checked } : f) }))} />Required</label>
                    <Button variant="ghost" size="icon" className="h-8 w-8 text-destructive shrink-0" onClick={() => removeFormField(i)}><Trash2 className="h-3.5 w-3.5" /></Button>
                  </div>
                  {(field.type === 'select' || field.type === 'radio') && <Input value={field.options || ''} onChange={(e) => setNewForm(p => ({ ...p, fields: p.fields.map((f, idx) => idx === i ? { ...f, options: e.target.value } : f) }))} placeholder="Options separated by commas, e.g. Basic, Premium, Enterprise" className="ml-0" />}
                  </div>
                ))}
              </div>
            </div>
            <div className="flex justify-end gap-2">
              <Button variant="outline" onClick={() => setFormOpen(false)}>Cancel</Button>
              <Button onClick={() => editingFormId ? updateFormMutation.mutate({ id: editingFormId, data: newForm }) : createFormMutation.mutate(newForm)} disabled={!newForm.name || createFormMutation.isPending || updateFormMutation.isPending}>
                {(createFormMutation.isPending || updateFormMutation.isPending) && <Loader2 className="h-4 w-4 mr-2 animate-spin" />}{editingFormId ? 'Save Form' : 'Create Form'}
              </Button>
            </div>
          </div>
        </DialogContent>
      </Dialog>

      {/* ── Create Table Dialog ── */}
      <Dialog open={tableOpen} onOpenChange={setTableOpen}>
        <DialogContent className="max-w-xl max-h-[80vh] overflow-y-auto">
          <DialogHeader><DialogTitle>Create Database Table</DialogTitle></DialogHeader>
          <div className="space-y-4 py-1">
            <div className="grid grid-cols-2 gap-3">
              <div className="space-y-1.5"><Label>Table Name (internal)</Label><Input value={newTable.name} onChange={(e) => setNewTable(p => ({ ...p, name: e.target.value }))} placeholder="client_feedback" /></div>
              <div className="space-y-1.5"><Label>Display Label</Label><Input value={newTable.label} onChange={(e) => setNewTable(p => ({ ...p, label: e.target.value }))} placeholder="Client Feedback" /></div>
            </div>
            <div className="space-y-2">
              <div className="flex items-center justify-between"><Label>Fields</Label><Button size="sm" variant="outline" className="h-7 text-xs" onClick={addTableField}><Plus className="h-3.5 w-3.5 mr-1" />Add Field</Button></div>
              <div className="space-y-2 max-h-48 overflow-y-auto">
                {newTable.fields.map((field, i) => (
                  <div key={i} className="flex items-center gap-2">
                    <Input value={field.label} onChange={(e) => setNewTable(p => ({ ...p, fields: p.fields.map((f, idx) => idx === i ? { ...f, label: e.target.value, name: e.target.value.toLowerCase().replace(/\s+/g, '_') } : f) }))} placeholder="Field label" className="flex-1" />
                    <Select value={field.type} onValueChange={(v) => setNewTable(p => ({ ...p, fields: p.fields.map((f, idx) => idx === i ? { ...f, type: v } : f) }))}>
                      <SelectTrigger className="w-32"><SelectValue /></SelectTrigger>
                      <SelectContent>{FIELD_TYPES.map((t) => <SelectItem key={t.value} value={t.value}>{t.label}</SelectItem>)}</SelectContent>
                    </Select>
                    <Button variant="ghost" size="icon" className="h-8 w-8 text-destructive shrink-0" onClick={() => removeTableField(i)}><Trash2 className="h-3.5 w-3.5" /></Button>
                  </div>
                ))}
              </div>
            </div>
            <div className="flex justify-end gap-2">
              <Button variant="outline" onClick={() => setTableOpen(false)}>Cancel</Button>
              <Button onClick={() => createTableMutation.mutate(newTable)} disabled={!newTable.name || createTableMutation.isPending}>
                {createTableMutation.isPending && <Loader2 className="h-4 w-4 mr-2 animate-spin" />}Create Table
              </Button>
            </div>
          </div>
        </DialogContent>
      </Dialog>
    </div>
  );
}
